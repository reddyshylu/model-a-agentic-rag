"""Central settings. Values come from the .env file (see .env.example)."""
import os
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

def _load_env(path: Path) -> None:
    """Read KEY=value lines from .env (no extra package needed). This project's .env wins over
    older values left in the terminal or Windows (for example from the Week 2 project)."""
    if not path.exists():
        return
    for raw in path.read_text(encoding="utf-8-sig").splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        key, value = key.strip(), value.strip().strip('"').strip("'")
        if key:
            os.environ[key] = value


